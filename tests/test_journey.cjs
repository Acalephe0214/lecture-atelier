const assert=require('node:assert/strict');
const {STEPS,plan}=require('../static/journey.js');
const copy=require('../static/ui-copy.js');
const {translator,diagnostics}=require('../static/i18n.js');
let checks=0;const check=fn=>{fn();checks++};
check(()=>assert.equal(STEPS.length,5));
for(const step of STEPS)for(const field of ['title','result','where','output','action'])check(()=>{assert.equal(step[field].length,2);assert.ok(step[field].every(v=>typeof v==='string'&&v.length));assert.ok(!/\p{Script=Han}/u.test(step[field][1]))});
check(()=>assert.deepEqual(plan({lecture:null}),{current:1,available:[true,false,false,false,false],complete:[false,false,false,false,false]}));
check(()=>assert.equal(plan({lecture:{audio:{name:'a.wav'}}}).current,2));
const lecture={segments:[{text:'私人的中文，不要翻译',review_status:'unreviewed'}],notes:[]};
check(()=>assert.equal(plan({lecture}).current,3));
check(()=>assert.equal(lecture.segments[0].text,'私人的中文，不要翻译'));
lecture.segments[0].review_status='verified';
check(()=>assert.equal(plan({lecture}).current,4));
lecture.generation={mode:'local'};
check(()=>assert.equal(plan({lecture}).complete[3],false));
lecture.overview={summary:{}};
check(()=>assert.equal(plan({lecture}).current,5));
for(const value of Object.values(copy))check(()=>{assert.ok(value.zh!==undefined&&value.en!==undefined);assert.ok(!/\p{Script=Han}/u.test(value.en))});
const en=translator({},'en',copy),zh=translator({},'zh',copy);
check(()=>assert.equal(zh.t('不复用断点重跑'),'从头重新转写'));
check(()=>assert.equal(en.t('不复用断点重跑'),'Restart transcription'));
check(()=>assert.equal(zh.t('私人的中文，不要翻译'),'私人的中文，不要翻译'));
check(()=>assert.equal(en.t('私人的中文，不要翻译'),'私人的中文，不要翻译'));
check(()=>assert.equal(diagnostics({},'en',copy).diagnostic('材料已更新，请重新打开移除确认。'),'Material changed. Open the removal confirmation again.'));
console.log(`${checks} journey and concise-copy checks passed`);
